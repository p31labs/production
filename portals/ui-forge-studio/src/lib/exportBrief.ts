/**
 * exportBrief.ts — the exportable text description (Stage 2 deliverable).
 *
 * Renders a DesignBrief (JSON source-of-truth) into a human-readable,
 * exportable Markdown document — the "text-only description" the operator
 * owns and can hand to an agent or a reviewer. The JSON is the source; the
 * markdown is the export (the dual-format pattern: JSON editable, markdown
 * portable).
 */
import type { DesignBrief } from './studioStore';

/** The 4-layer DesignBrief → markdown. */
export function briefToMarkdown(brief: DesignBrief): string {
  const lines: string[] = [];

  lines.push(`# Design Brief — ${brief.title}`);
  lines.push('');
  lines.push('## Goal');
  lines.push(brief.goal || '(to be refined)');
  lines.push('');

  lines.push('## Structure');
  if (brief.structure.length) {
    for (const s of brief.structure) lines.push(`- ${s}`);
  } else {
    lines.push('(none yet)');
  }
  lines.push('');

  lines.push('## Constraints');
  if (brief.constraints.length) {
    for (const c of brief.constraints) lines.push(`- ${c}`);
  } else {
    lines.push('(none yet)');
  }
  lines.push('');

  lines.push('## Entities');
  if (brief.entities.length) {
    for (const e of brief.entities) {
      const fields = (e.fields ?? []).map((f) => `${f.name}:${f.type}`).join(', ');
      lines.push(`- **${e.name}** ${fields ? `(${fields})` : ''}`);
    }
  } else {
    lines.push('(none yet)');
  }
  lines.push('');

  lines.push('## Actions');
  if (brief.actions.length) {
    for (const a of brief.actions) lines.push(`- ${a.name}`);
  } else {
    lines.push('(none yet)');
  }
  lines.push('');

  lines.push('---');
  lines.push('*Generated by P31 UI Forge. JSON source-of-truth; this markdown is the exportable description.*');

  return lines.join('\n');
}

/** Trigger a download of the brief as DesignBrief.md. */
export function downloadBrief(brief: DesignBrief): void {
  const md = briefToMarkdown(brief);
  const blob = new Blob([md], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'DesignBrief.md';
  a.click();
  URL.revokeObjectURL(url);
}