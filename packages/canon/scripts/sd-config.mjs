#!/usr/bin/env node
/**
 * @p31ca/canon — sd-config.mjs (Style Dictionary **v5** pipeline)
 *
 * The transformer between the DTCG export (tokens/tokens.dtc.json) and the
 * three runtime artifacts:
 *
 *   1. dist/tokens.css          — the layered token sheet (:root +
 *                                 [data-theme="<id>"] × 11 + the rose mode
 *                                 block). SD v5 is the GENERATOR of the
 *                                 portable-token layer. The css-emit layer
 *                                 (calc/clamp/var/blur/color-mix/hex values
 *                                 with no portable DTCG form, COMPAT_ROOT,
 *                                 CONDITIONAL_CSS) is appended by
 *                                 gen-tokens.mjs — a documented architectural
 *                                 split, not a parallel source.
 *   2. dist/tokens.mjs          — typed JS (JSDoc) mirror, runtime values.
 *   3. tokens/dist/tokens.resolved.json — agent-consumable resolved tree
 *                                 ({value,unit} / {colorSpace,components}
 *                                 shape preserved from the pre-v5 export).
 *
 * SD reads ONLY the DTCG file. gen-tokens.mjs attaches each token's raw CSS
 * string as `$extensions.p31.css` (+ `$extensions.p31.themesCss` for the
 * per-theme semantic overrides) so the emitted CSS is byte-identical to the
 * store's values — no reserialization, no value drift.
 *
 * SD v5 is required (>= 5.3.0) for native OKLCH handling; Node 24 on-box.
 */
import { join } from 'node:path'
import StyleDictionary from 'style-dictionary'
import { THEME_IDS, DEFAULT_THEME } from '../src/theming/theme-store.ts'

// ── token tree helpers ──────────────────────────────────────────────────
// A dictionary.tokens leaf is any object carrying $value; groups do not.
// Structured $value objects ({value,unit} / {colorSpace,components}) never
// appear at group level, so $value-presence is a safe discriminator.
function* walkLeaves(node, path = []) {
  for (const [k, v] of Object.entries(node ?? {})) {
    if (k.startsWith('$')) continue
    if (!v || typeof v !== 'object') continue
    if ('$value' in v) yield [k, v, path]
    else yield* walkLeaves(v, [...path, k])
  }
}

const dashName = (key, path) => `--p31-${[...path, key].join('-')}`

/** The runtime CSS value: gen-tokens' raw string, else a safe fallback. */
function cssValue(token) {
  const css = token?.$extensions?.p31?.css
  if (typeof css === 'string' && css.length) return css
  const v = token?.$value
  if (typeof v === 'string') return v
  if (Array.isArray(v)) return v.join(', ')
  if (typeof v === 'number') return String(v)
  if (v && typeof v === 'object' && 'value' in v && 'unit' in v) return `${v.value}${v.unit}`
  if (v && typeof v === 'object' && 'colorSpace' in v) {
    const [L, C, H] = v.components ?? []
    const a = v.alpha !== undefined ? ` / ${v.alpha}` : ''
    return `oklch(${L} ${C} ${H}${a})`
  }
  return String(v ?? '')
}

/** Semantic slots = the NESTED p31 leaves (flat p31 keys are primitives). */
function semanticEntries(p31Tree) {
  const out = []
  for (const [k, token, path] of walkLeaves(p31Tree)) {
    if (path.length === 0) continue
    out.push([k, token, path])
  }
  return out
}

// ── formats ─────────────────────────────────────────────────────────────

StyleDictionary.registerFormat({
  name: 'p31/css-layer',
  format: async ({ dictionary }) => {
    const dt = dictionary.tokens
    const p31 = dt.p31 ?? {}
    const defaultTheme = dt.themes?.[DEFAULT_THEME]?.p31 ?? {}

    const header = `/**
 * @p31ca/canon — tokens.css. Do not edit directly; run \`pnpm build:tokens\`.
 * Generated by Style Dictionary v5 from tokens/tokens.dtc.json
 * (single source of truth: src/theming/theme-store.ts).
 * Names are the runtime --p31-* contract; values change per theme.
 * Accent MODES ride the same semantic tier: cyan is canonical, rose is the
 * [data-theme="rose"] mode (ratified unification D1 — never a fork).
 */

@layer legacy, canon.tokens, canon.components, canon.layout, shell, face;

@layer canon.tokens {
`

    const block = (selector, entries) => {
      const lines = entries
        .map(([k, token, path]) => `  ${dashName(k, path)}: ${cssValue(token)};`)
        .join('\n')
      return `${selector} {\n${lines}\n}\n`
    }

    // :root — p31.* (primitives + semantic default) then the default theme
    // palette (same cascade order as the pre-v5 export: palette wins).
    let css = header
    css += block(':root', [...walkLeaves(p31), ...walkLeaves(defaultTheme)])

    for (const id of THEME_IDS) {
      const palette = dt.themes?.[id]?.p31 ?? {}
      const entries = [...walkLeaves(palette)]
      // Per-theme semantic overrides — raw store values, later-in-block wins
      // over the palette for dashed-name collisions (pre-v5 order preserved).
      for (const [k, token, path] of semanticEntries(p31)) {
        const raw = token?.$extensions?.p31?.themesCss?.[id]
        if (typeof raw === 'string') {
          entries.push([k, { $extensions: { p31: { css: raw } } }, path])
        }
      }
      css += '\n' + block(`[data-theme="${id}"]`, entries)
    }

    // Rose accent mode — DTCG $extensions.mode: "rose" → [data-theme="rose"].
    const rose = dt.modes?.rose ?? {}
    css += '\n' + block('[data-theme="rose"]', [...walkLeaves(rose)])
    css += '}\n'
    return css
  },
})

StyleDictionary.registerFormat({
  name: 'p31/mjs',
  format: async ({ dictionary }) => {
    const dt = dictionary.tokens
    const p31 = dt.p31 ?? {}
    const entries = [...walkLeaves(p31)].map(([k, token, path]) => [
      dashName(k, path),
      cssValue(token),
    ])
    const rose = [...walkLeaves(dt.modes?.rose ?? {})].map(([k, token, path]) => [
      dashName(k, path),
      cssValue(token),
    ])
    const nameUnion = entries.map(([n]) => `'${n}'`).join(' | ')
    const kv = (rows) => rows.map(([n, v]) => `  ${JSON.stringify(n)}: ${JSON.stringify(v)}`).join(',\n')
    return `/**
 * @p31ca/canon — tokens.mjs (GENERATED by Style Dictionary v5 — do not edit).
 * Typed JS mirror of tokens/tokens.dtc.json; values are the runtime strings
 * as emitted in dist/tokens.css (the :root contract + the rose mode).
 *
 * @typedef {${nameUnion}} P31TokenName
 */

const tokens = Object.freeze({
${kv(entries)}
})

/** Rose accent mode — the [data-theme="rose"] override set (unification D1). */
const roseMode = Object.freeze({
${kv(rose)}
})

export { tokens, roseMode }
export default tokens
`
  },
})

StyleDictionary.registerFormat({
  name: 'p31/resolved',
  format: async ({ dictionary, options }) => {
    const dt = dictionary.tokens
    const meta = options?.meta ?? {}

    /** Resolve '{p31.x}' alias refs to the target token's structured value. */
    function resolveRef(ref, seen = new Set()) {
      if (seen.has(ref)) return ref
      seen.add(ref)
      const seg = ref.slice(1, -1).split('.')
      let node = dt
      for (const s of seg) node = node?.[s]
      if (!node) return ref
      if (typeof node.$value === 'string' && node.$value.startsWith('{') && node.$value.endsWith('}')) {
        return resolveRef(node.$value, seen)
      }
      return node.$value
    }

    function buildTree(node) {
      const out = {}
      for (const [k, v] of Object.entries(node ?? {})) {
        if (k.startsWith('$')) continue
        if (!v || typeof v !== 'object' || Array.isArray(v)) continue
        if ('$value' in v) {
          let val = v.$value
          if (typeof val === 'string' && val.startsWith('{') && val.endsWith('}')) {
            val = resolveRef(val)
          }
          out[k] = val
        } else {
          out[k] = buildTree(v)
        }
      }
      return out
    }

    return JSON.stringify(
      {
        $schema: meta.$schema,
        $extensions: meta.$extensions,
        p31: buildTree(dt.p31),
        themes: buildTree(dt.themes),
        modes: buildTree(dt.modes),
        component: buildTree(dt.component),
      },
      null,
      2,
    ) + '\n'
  },
})

// ── the build ───────────────────────────────────────────────────────────

/**
 * Run SD v5 over the DTCG export.
 * @param {{ root: string, meta: object }} opts  root = packages/canon path
 * @returns {Promise<{ built: boolean }>}
 */
export async function buildTokenArtifacts({ root, meta }) {
  const sd = new StyleDictionary({
    usesDtcg: true,
    source: [join(root, 'tokens', 'tokens.dtc.json')],
    platforms: {
      p31: {
        buildPath: join(root, 'dist', '/'),
        files: [
          { destination: 'tokens.css', format: 'p31/css-layer' },
          { destination: 'tokens.mjs', format: 'p31/mjs' },
          {
            destination: join('..', 'tokens', 'dist', 'tokens.resolved.json'),
            format: 'p31/resolved',
            options: { meta },
          },
        ],
      },
    },
  })
  await sd.hasInitialized
  const out = await sd.buildAllPlatforms()
  return { built: Boolean(out?.p31) }
}