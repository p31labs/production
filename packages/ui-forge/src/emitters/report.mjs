/**
 * emitters/report.mjs — the report target emitter.
 *
 * Emits the research-report artifact: the markdown report itself plus a README
 * describing the two files. This is Workflow A's native output — not a React
 * target — and proves the registry handles heterogeneous artifact shapes, not
 * just component trees.
 *
 * Self-contained by design: the P31-HANDOFF block already lives inside the
 * report markdown, so this emitter does not parse it. Parsing is the
 * convergence pipeline's job (`tools (1)/phos-forge/handoff.mjs` →
 * `reportToSpec`), which is the single source of truth for the block format.
 * No cross-package import here — no parenthesized-path fragility.
 *
 * Deterministic: same report → byte-identical files.
 */
export function emitReport({ report }, { name }) {
  if (typeof report !== 'string' || report.trim() === '') {
    throw new Error('emit-report: input.report must be a non-empty string');
  }
  return {
    files: {
      'report.md': report.endsWith('\n') ? report : report + '\n',
      'README.md': [
        `# ${name} — research report`,
        '',
        'Generated by P31 UI Forge (Workflow A).',
        '',
        '## Files',
        '',
        '- `report.md` — the full report (executive summary, body, sources),',
        '  including the machine-readable `P31-HANDOFF` block.',
        '',
        '## Next',
        '',
        'Feed the report to the tetrahedron (Workflow B) to build the artifact.',
        'The handoff block is parsed by the convergence pipeline — no manual step.',
        '',
      ].join('\n'),
    },
  };
}

export default emitReport;