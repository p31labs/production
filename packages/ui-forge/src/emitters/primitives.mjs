/**
 * emitters/primitives.mjs — the shared deterministic emission primitives.
 *
 * Every emitter (website, app) builds on these. They live in their own module
 * so the emitters never import the dispatch layer — no circular dependency.
 * All pure: same input → same string, no filesystem, no network, no LLM.
 */

/** Emit a single JSX prop. Strings quote; numbers/booleans bare; null/false drop. */
export function jsxProp(key, value) {
  if (value === undefined || value === null || value === false) return null;
  if (value === true) return key;
  if (typeof value === 'string') return `${key}=${JSON.stringify(value)}`;
  if (typeof value === 'number') return `${key}={${value}}`;
  return `${key}={${JSON.stringify(value)}}`;
}

/** Recursively emit a JSX element. `indent` prefixes every line; children inherit +2. */
export function jsxNode(node, indent = '') {
  const type = node?.type ?? 'div';
  const props = node?.props ?? {};
  const propStrs = Object.entries(props).map(([k, v]) => jsxProp(k, v)).filter(Boolean);
  const children = Array.isArray(node?.children) && node.children.length > 0 ? node.children : null;
  const open = `${indent}<${type}${propStrs.length ? ' ' + propStrs.join(' ') : ''}`;
  if (children) {
    const childStr = children.map((c) => jsxNode(c, indent + '  ')).join('\n');
    return `${open}>\n${childStr}\n${indent}</${type}>`;
  }
  return `${open} />`;
}

/** Collect the set of component types used in the tree (for the import line). */
export function collectTypes(tree) {
  const types = new Set();
  const walk = (n) => {
    if (n?.type) types.add(n.type);
    for (const c of n?.children ?? []) walk(c);
  };
  walk(tree);
  return [...types];
}

/** Emit the App.tsx source for a tree. Shared by the website + app emitters. */
export function emitAppTsx(tree) {
  const types = collectTypes(tree);
  return [
    'import {',
    `  ${types.join(',\n  ')},`,
    "} from '@p31ca/design-core/compositions';",
    '',
    'export default function App() {',
    '  return (',
    `    ${jsxNode(tree, '  ')}`,
    '  );',
    '}',
    '',
  ].join('\n');
}

/** The base Vite + React project files — shared scaffolding for any React target.
 *  `dependencies` supplies the runtime deps; `extraFiles` supplies the target's
 *  src/ files. Returns a `files` map (relative path → content). */
export function baseReactProject(name, dependencies, extraFiles = {}) {
  return {
    'package.json': JSON.stringify({
      name,
      private: true,
      version: '0.0.0',
      type: 'module',
      scripts: { dev: 'vite', build: 'vite build', preview: 'vite preview' },
      dependencies: {
        react: '^18.3.1',
        'react-dom': '^18.3.1',
        ...dependencies,
      },
      devDependencies: {
        '@types/react': '^18.3.0',
        '@types/react-dom': '^18.3.0',
        '@vitejs/plugin-react': '^4.3.0',
        vite: '^5.4.0',
        typescript: '^5.5.0',
      },
    }, null, 2) + '\n',
    'vite.config.ts': [
      "import { defineConfig } from 'vite';",
      "import react from '@vitejs/plugin-react';",
      '',
      'export default defineConfig({ plugins: [react()] });',
      '',
    ].join('\n'),
    'index.html': [
      '<!doctype html>',
      '<html lang="en">',
      '  <head>',
      '    <meta charset="UTF-8" />',
      '    <meta name="viewport" content="width=device-width, initial-scale=1.0" />',
      `    <title>${name}</title>`,
      '  </head>',
      '  <body>',
      '    <div id="root"></div>',
      '    <script type="module" src="/src/main.tsx"></script>',
      '  </body>',
      '</html>',
      '',
    ].join('\n'),
    'README.md': [
      `# ${name}`,
      '',
      'Generated by P31 UI Forge.',
      '',
      '## Build',
      '',
      '```bash',
      'npm install',
      'npm run build',
      'npm run dev',
      '```',
      '',
      '> **Use npm, not pnpm.** pnpm 11 blocks esbuild\'s postinstall script without',
      '> explicit approval; npm runs it by default.',
      '',
    ].join('\n'),
    ...extraFiles,
  };
}