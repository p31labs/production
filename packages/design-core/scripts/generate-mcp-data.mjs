#!/usr/bin/env node
/**
 * @file Generate embedded MCP data files from recipes.css and tokens.yml.
 *
 * Outputs:
 *   src/mcp/recipes-data.ts   — recipe class map + full CSS text
 *   src/mcp/tokens-data.ts    — flattened token paths with resolved values
 *
 * Usage:
 *   node scripts/generate-mcp-data.mjs
 */

import { readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';
import YAML from 'yaml';

const ROOT = resolve(import.meta.dirname, '..', '..', '..');
const RECIPES_SRC = resolve(ROOT, 'packages', 'design-core', 'src/css/recipes.css');
const TOKENS_SRC = resolve(ROOT, 'cli/tokens/tokens.yml');
const MCP_DIR = resolve(ROOT, 'packages', 'design-core', 'src/mcp');

function cssVarName(pathStr) {
  return '--p31-' + pathStr.replace(/\./g, '-');
}

function resolveTokenValue(pathStr, tokens, seen = new Set()) {
  if (seen.has(pathStr)) return `{${pathStr}}`;
  seen.add(pathStr);

  // Try direct path first, then primitive./semantic. prefixed paths
  const candidates = [pathStr, `primitive.${pathStr}`, `semantic.${pathStr}`];
  let node = null;
  for (const candidate of candidates) {
    const parts = candidate.split('.');
    let current = tokens;
    for (const part of parts) {
      if (current == null || typeof current !== 'object') { current = null; break; }
      current = current[part];
    }
    if (current != null) { node = current; break; }
  }

  if (node == null) return `{${pathStr}}`;

  if (typeof node === 'string') {
    return node.replace(/\{([^}]+)\}/g, (_, ref) => resolveTokenValue(ref, tokens, seen));
  }

  if (typeof node === 'object') {
    if (node.$value) {
      return String(node.$value).replace(/\{([^}]+)\}/g, (_, ref) => resolveTokenValue(ref, tokens, seen));
    }
    return JSON.stringify(node);
  }

  return String(node);
}

function flattenTokens(tokens, prefix = '') {
  const result = [];
  for (const [key, value] of Object.entries(tokens)) {
    if (key.startsWith('$')) continue;
    const path = prefix ? `${prefix}.${key}` : key;
    if (value && typeof value === 'object' && !Array.isArray(value) && !value.$value) {
      result.push(...flattenTokens(value, path));
    } else {
      const raw = typeof value === 'object' ? value.$value ?? JSON.stringify(value) : value;
      result.push({ path, raw: String(raw) });
    }
  }
  return result;
}

// ─── Recipes ────────────────────────────────────────────────────────────────

const recipesText = readFileSync(RECIPES_SRC, 'utf-8');
const recipeMap = {};
const recipePositions = {};
const classRegex = /\.([a-zA-Z0-9_-]+)\s*\{/g;
let match;
while ((match = classRegex.exec(recipesText)) !== null) {
  const name = match[1];
  const start = match.index;
  const openBrace = recipesText.indexOf('{', start);
  const closeBrace = findMatchingBrace(recipesText, openBrace);
    recipeMap[name] = recipesText.slice(start, closeBrace + 1).trim();
    if (!(name in recipePositions)) recipePositions[name] = start;
  }

// Derive recipe categories from CSS section headers: /* ─── Section ─── */
const sectionRegex = /\/\*\s*───\s*(.+?)\s*───\s*\*\//g;
const sections = [];
let sectionMatch;
while ((sectionMatch = sectionRegex.exec(recipesText)) !== null) {
  sections.push({ name: sectionMatch[1], index: sectionMatch.index });
}
const recipeCategories = {};
for (const [name, startIndex] of Object.entries(recipePositions)) {
  let current = 'Uncategorized';
  for (const section of sections) {
    if (section.index < startIndex) current = section.name;
    else break;
  }
  (recipeCategories[current] ??= []).push(name);
}

function findMatchingBrace(text, openIndex) {
  let depth = 0;
  for (let i = openIndex; i < text.length; i++) {
    if (text[i] === '{') depth++;
    else if (text[i] === '}') {
      depth--;
      if (depth === 0) return i;
    }
  }
  return text.length;
}

const recipesDataTs = `// Auto-generated by scripts/generate-mcp-data.mjs — DO NOT EDIT
export const RECIPES_CSS = ${JSON.stringify(recipesText)};
export const RECIPE_MAP: Record<string, string> = ${JSON.stringify(recipeMap, null, 2)};
export const RECIPE_NAMES = ${JSON.stringify(Object.keys(recipeMap))};
export const RECIPE_CATEGORIES: Record<string, string[]> = ${JSON.stringify(recipeCategories, null, 2)};
`;

writeFileSync(resolve(MCP_DIR, 'recipes-data.ts'), recipesDataTs);
console.log(`✅ Generated recipes-data.ts (${Object.keys(recipeMap).length} recipes)`);

// ─── Tokens ─────────────────────────────────────────────────────────────────

const tokensText = readFileSync(TOKENS_SRC, 'utf-8');
const tokens = YAML.parse(tokensText);
const primitive = tokens.primitive || {};
const semantic = tokens.semantic || {};
const allTokens = { ...primitive, ...semantic };

const flat = flattenTokens(allTokens);
const tokenEntries = flat.map(({ path, raw }) => {
  const resolved = resolveTokenValue(path, tokens);
  return {
    path,
    cssVar: cssVarName(path),
    value: resolved,
    raw,
  };
});

const tokensDataTs = `// Auto-generated by scripts/generate-mcp-data.mjs — DO NOT EDIT
export const TOKENS_DATA = ${JSON.stringify(tokenEntries, null, 2)} as const;
export const TOKEN_MAP: Record<string, { cssVar: string; value: string; raw: string }> = ${JSON.stringify(Object.fromEntries(tokenEntries.map(t => [t.path, { cssVar: t.cssVar, value: t.value, raw: t.raw }])))};
`;

writeFileSync(resolve(MCP_DIR, 'tokens-data.ts'), tokensDataTs);
console.log(`✅ Generated tokens-data.ts (${tokenEntries.length} tokens)`);
