/** Pre-answered enterprise questionnaire — ten questions, no secrets. */
const QA = [
  { q: 'How is the portal hosted?', a: 'Cloudflare Workers edge on a sovereign multi-worker mesh (portal, MCP, BTCPay, p31-ci). Serverless — no self-hosted OS to patch; platform-level hardening handled by Cloudflare. Source is open.' },
  { q: 'Is data encrypted at rest and in transit?', a: 'Yes. TLS 1.2+ in transit on every route. Data at rest lives in Cloudflare D1 (encrypted at rest by the platform); secrets never reach durable storage and stay in-memory per isolate.' },
  { q: 'How are users authenticated?', a: 'Three layers: passkeys (WebAuthn) bound to a sovereign DID, HS256 role tokens (viewer/operator/admin), and optional Cloudflare Access JWT validation. See docs/ZERO-TRUST.md.' },
  { q: 'How is authorization enforced?', a: 'RBAC with viewer/operator/admin roles. Admin write routes (config, entitlements, LOVE issuance) require an admin role token; operators cover operator routes; Access JWTs map to viewer/operator only.' },
  { q: 'How are keys managed and rotated?', a: 'Credential rotation runbook in docs/SECURITY.md: full rotation after every agent session that touches secrets, least-privilege scopes (CDP seller-only, BTCPay read/create-only), secrets never committed.' },
  { q: 'What is the incident-response posture?', a: 'Continuous runtime invariants (/api/health/invariants), DORA metrics (change failure rate, MTTR), an availability SLO, and a hash-chained ledger that makes tampering detectable. Post-incident review follows blameless runbooks.' },
  { q: 'How is the software supply chain protected?', a: 'A CycloneDX 1.5 SBOM is generated by scripts/sbom.mjs (via cdxgen when available) at dist/trust/sbom.cdx.json with a sha256 digest. Production signing uses in-house ML-DSA-65 + Ed25519 hybrid keys (p31-crypto) as the trust anchor.' },
  { q: 'How long is data retained, and what PII is stored?', a: 'Append-only hash-chained ledger with minimal PII. Identity stays in-browser as a DID; D1 holds hashes and payment metadata, not raw credentials.' },
  { q: 'What compliance certifications apply?', a: 'SOC 2 Trust Services Criteria (Security) readiness with a generated controls index (dist/trust/controls-index.json); CPA attestation is planned. Controls map to CC3, CC6, CC7, CC8.' },
  { q: 'How can an enterprise get more detail?', a: 'Reach the operator through the sovereign DID on the Profile surface, or open a request against this repository. All evidence endpoints are public and the codebase is open source.' },
];

export default function TrustSurface() {
  const invariants = useQuery(invariantsQuery);
  const dora = useQuery(doraMetricsQuery);

  const inv = invariants.data;
  const d = dora.data;
  const okCount = inv ? inv.invariants.filter((i) => i.status === 'ok').length : null;
  const failCount = inv ? inv.invariants.filter((i) => i.status === 'fail').length : null;
  const invSt = queryStatus(invariants);
  const doraSt = queryStatus(dora);

  return (
    <div className="surface-page">
      <header className="surface-head">
        <div>
          <h2 className="surface-title">Trust Center</h2>
          <p className="surface-sub">
            Sovereign, open-source, community-funded. Security posture, evidence library, and pre-answered questionnaires in one place.
          </p>
        </div>
        <div className="surface-actions">
          <span className={`integrity-badge${inv?.healthy === false ? ' integrity-badge--fail' : ''}`}>
            {invariants.isPending ? 'Checking…' : inv?.healthy ? '✓ Posture green' : '✗ Invariant failure'}
          </span>
        </div>
      </header>

      {invariants.isError && <StatusBanner kind="error">Invariant check unreachable — posture evidence pending.</StatusBanner>}

      <h3 className="surface-card-title" style={{ marginBottom: 'var(--p31-space-3)' }}>Security posture</h3>
      <div className="metric-grid">
        <MetricCard
          label="Runtime invariants"
          value={failCount == null ? '…' : failCount === 0 ? `${okCount} ok` : `${failCount} fail`}
          sub="hash-chain / allocator / config reachability"
          accent={failCount == null ? 'cyan' : failCount === 0 ? 'green' : 'red'}
          status={invSt.status}
          lastUpdated={invariants.dataUpdatedAt ? new Date(invariants.dataUpdatedAt) : null}
        />
        <MetricCard
          label="DORA metrics"
          value={d ? `${d.deploy_frequency.total} deploys` : '…'}
          sub={d?.change_failure_rate != null ? `CFR ${(d.change_failure_rate * 100).toFixed(1)}% · 7d` : '7-day window'}
          accent="gold"
          status={doraSt.status}
          lastUpdated={dora.dataUpdatedAt ? new Date(dora.dataUpdatedAt) : null}
        />
        <MetricCard
          label="SBT registry"
          value="Hash-chained"
          sub="per-DID SHA-256 soulbound token chain"
          accent="violet"
          status="live"
        />
        <MetricCard
          label="RBAC"
          value="viewer / operator / admin"
          sub="HS256 role tokens + WebAuthn + Access JWT"
          accent="cyan"
          status="live"
        />
      </div>

      <h3 className="surface-card-title" style={{ marginBottom: 'var(--p31-space-3)' }}>Evidence library</h3>
      <div className="row-list">
        {EVIDENCE.map((e) => (
          <div key={e.href} className="row-card">
            <div className="row-card__head">
              <a className="row-card__title mono" href={e.href}>{e.label}</a>
            </div>
            <div className="row-card__meta">{e.desc}</div>
          </div>
        ))}
      </div>

      <h3 className="surface-card-title" style={{ marginBottom: 'var(--p31-space-3)' }}>Pre-answered questionnaire</h3>
      <div className="row-list">
        {QA.map((item) => (
          <div key={item.q} className="row-card">
            <div className="row-card__head">
              <span className="row-card__title">{item.q}</span>
            </div>
            <div className="row-card__meta">{item.a}</div>
          </div>
        ))}
      </div>
    </div>
  );
}