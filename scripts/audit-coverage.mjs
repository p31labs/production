#!/usr/bin/env node
/**
 * audit-coverage.mjs — Tetrahedron Face 1 (V1·V2·V3).
 *
 * "Is every captured file sorted and tagged?"
 *
 * Every significant file must carry a P31-HEADER (the V1 tag). Files without
 * a header are "unfiled" — they cannot be sorted (V2) or shaped (V3).
 * This face returns true iff no unfiled authored file exists in the substrate.
 *
 * Usage: node scripts/audit-coverage.mjs
 */
import { readdirSync, readFileSync, lstatSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;

// The substrate is the set of files that MUST be tagged — the active authored
// layers where V1 CAPTURE applies (plan artifacts, fix-plans, the workspace
// substrate). The broader legacy docs/ corpus is reference material that
// predates the convention (handled by the W9 backlog, not this gate).
const REQUIRED_DIRS = ['docs/plans', 'docs/fix-plans', 'scripts', '.workspace'];
const ROOT_FILES = ['AGENTS.md', 'STATE.md', 'INBOX.md', 'HISTORY.md'];
const EXEMPT = [/node_modules/, /\.git\//, /dist\//, /vendor\//, /target\//];

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    const st = lstatSync(p);
    if (st.isSymbolicLink()) continue;
    if (st.isDirectory()) {
      if (/node_modules|\.git|dist|target|vendor|( \(1\)$)/.test(entry)) continue;
      walk(p, out);
    } else if (/\.(md|json|yaml|yml)$/.test(p)) {
      out.push(p);
    }
  }
  return out;
}

let unfiled = 0;
// Coverage governs AUTHORED markdown work-products (plans, fix-plans, state).
// JS scripts use JSDoc, not markdown headers; the generated manifest is
// derived state (regenerated by probe-workspace, not hand-authored).
const checkFile = (file) => {
  if (/\.(js|mjs|ts|tsx)$/.test(file)) return;
  if (file.endsWith('.workspace/manifest.json') || file.endsWith('.workspace/repos.yaml')) return;
  const content = readFileSync(file, 'utf8');
  if (!content.includes('P31-HEADER')) {
    console.error(`COVERAGE: unfiled — ${file}`);
    unfiled++;
  }
};
for (const rf of ROOT_FILES) {
  const p = join(ROOT, rf);
  try { checkFile(p); } catch { /* missing */ }
}
for (const dir of REQUIRED_DIRS) {
  const p = join(ROOT, dir);
  try {
    for (const file of walk(p)) checkFile(file);
  } catch { /* dir missing */ }
}

if (unfiled > 0) {
  console.error(`\naudit-coverage: FAIL — ${unfiled} unfiled files (must be tagged with a P31-HEADER)`);
  process.exit(1);
}
console.log('audit-coverage: pass — every captured file is tagged');