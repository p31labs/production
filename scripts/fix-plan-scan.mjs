#!/usr/bin/env node
/**
 * fix-plan-scan.mjs — the ownership contract sensor.
 *
 * "It's all our work. Every problem is filed work."
 *
 * Fails the gate on:
 *   1. A file containing TODO/FIXME/XXX/HACK without a matching fix-plan
 *   2. An open fix-plan older than 7 commits with no resolution
 *   3. An orphaned known-broken marker
 *
 * The negative control: a deliberately-planted unfiled TODO fails this scan,
 * proving the gate can fail.
 *
 * Usage: node scripts/fix-plan-scan.mjs [--strict]
 */
import { readdirSync, readFileSync, lstatSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const FIX_PLANS_DIR = join(ROOT, 'docs', 'fix-plans');

// --self-test proves the scan can FAIL: plant an unfiled TODO in a .ts file,
// run the scan in a subprocess, assert it exits 1, then clean up. Without this
// the "pass — no unfiled markers" line is a claim, not a proof.
if (process.argv.includes('--self-test')) {
  const { writeFileSync, rmSync } = await import('node:fs');
  const { execSync } = await import('node:child_process');
  const tmp = join(ROOT, 'workers', `negctrl-${Date.now()}.ts`);
  writeFileSync(tmp, '// TODO: negative control — planted to prove the scan fails\n');
  try {
    try {
      execSync(`node ${join(ROOT, 'scripts', 'fix-plan-scan.mjs')}`, { stdio: 'pipe' });
      console.error('✗ fix-plan-scan --self-test FAILED: scan passed with a planted unfiled TODO');
      process.exit(1);
    } catch (e) {
      if (e.status === 1) {
        console.log('✅ fix-plan-scan --self-test passed: scan fails on an unfiled TODO');
      } else {
        throw e;
      }
    }
  } finally {
    rmSync(tmp, { force: true });
  }
  process.exit(0);
}

// `XXX` is case-sensitive on purpose: lowercase `xxx` is a GLSL/vector
// swizzle (e.g. `offset.xxx`), not a marker. TODO/FIXME/HACK stay
// case-insensitive (they are authored as `todo`, `TODO`, `FIXME`, etc.).
const MARKERS = /\b(TODO|FIXME|HACK)\b/i;
const XXX_MARKER = /\bXXX\b/;
const EXEMPT = [
  /node_modules/, /\.git\//, /dist\//, /vendor\//, /target\//,
  /fix-plan-scan\.mjs$/, /AGENTS\.md$/, /STATE\.md$/, /INBOX\.md$/,
  /worker-configuration\.d\.ts$/,       // generated by wrangler
  /audit-temp-hacks\.mjs$/,             // intentional negative-control test
  /verify-cloudflare-token\.mjs$/,      // usage example uses xxx placeholder (docs, not code)
  /^scripts\/(namecheck|frontmatter|probe-workspace|audit-)/,
  /negative-controls\.mjs$/,   // the negative-control suite plants markers on purpose
  /docs\/fix-plans\//,                  // the filing mechanism itself
  // Reference material merged from docs (1)/ is archival, not active work.
  // The ownership contract (TODO/HACK must be filed) applies to code and the
  // active governance docs — enterprise/, plans/, research/, and the root
  // LESSONS/MONITORING/RUNBOOKS/PQC ledgers — not to the reference notes,
  // prompts, and inventories the merge brought in.
  /\/docs\/(?!(?:enterprise|plans|research|fix-plans)\/|(?:LESSONS|MONITORING|RUNBOOKS)\.md$|PQC-)/,
];

// The set of filenames already covered by a fix-plan (their markers are filed).
function filedFiles() {
  const filed = new Set();
  if (existsSync(FIX_PLANS_DIR)) {
    for (const entry of readdirSync(FIX_PLANS_DIR)) {
      if (!/\.md$/.test(entry)) continue;
      const content = readFileSync(join(FIX_PLANS_DIR, entry), 'utf8');
      // Recognize both section conventions ("## The bug" and "## Symptom")
      // and any source file extension (not just .mjs).
      const m = content.match(/^## (?:The bug|Symptom)\s*\n([\s\S]*?)(?=\n## )/m);
      if (m) {
        // Any file path mentioned in the section is filed (match basename).
        for (const path of m[1].matchAll(/`?([\w./-]+\.(?:mjs|ts|tsx|js|json))`?/g)) {
          filed.add(path[1].split('/').pop());
        }
      }
    }
  }
  return filed;
}

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    const st = lstatSync(p);
    if (st.isSymbolicLink()) continue;
    if (st.isDirectory()) {
      if (/node_modules|\.git|dist|target|vendor/.test(entry)) continue;
      walk(p, out);
    } else if (/\.(ts|tsx|js|mjs|md|json)$/.test(p)) {
      out.push(p);
    }
  }
  return out;
}

// Existing fix-plans (the ones on disk).
function listFixPlans() {
  const plans = new Set();
  if (existsSync(FIX_PLANS_DIR)) {
    for (const entry of readdirSync(FIX_PLANS_DIR)) {
      if (/\.md$/.test(entry)) plans.add(entry.replace(/\.md$/, ''));
    }
  }
  return plans;
}

let violations = 0;
const fixPlans = listFixPlans();
const filed = filedFiles();

// Scan the live authored dirs for unfiled markers.
const SCAN_DIRS = ['docs', 'scripts', 'portals/shell/src', 'packages/ui-forge/src', 'workers'];
for (const dir of SCAN_DIRS) {
  const p = join(ROOT, dir);
  try {
    for (const file of walk(p)) {
      if (EXEMPT.some((re) => re.test(file))) continue;
      // If the file already has a fix-plan, its markers are filed.
      if (filed.has(file.split('/').pop())) continue;
      const lines = readFileSync(file, 'utf8').split('\n');
      lines.forEach((line, i) => {
        const m = line.match(MARKERS) || line.match(XXX_MARKER);
        if (m) {
          const marker = m[0];
          // Check for a nearby fix-plan reference (e.g. "# fix-plan: <id>").
          const hasPlanRef = /fix-plan[:\s]*[\w-]+/.test(line) || line.includes('fix-plan:');
          if (!hasPlanRef) {
            console.error(`OWNERSHIP: unfiled ${marker} at ${file}:${i + 1} — write docs/fix-plans/<issue-id>.md`);
            violations++;
          }
        }
      });
    }
  } catch { /* dir missing */ }
}

// Open fix-plans: a plan is overdue when it's open (no resolution) and was
// created more than 7 days ago. Freshly-filed plans (this session) are fine.
try {
  const { execSync } = await import('node:child_process');
  const now = Date.now();
  for (const plan of fixPlans) {
    const p = join(FIX_PLANS_DIR, `${plan}.md`);
    const content = readFileSync(p, 'utf8');
    // A resolved plan carries a "status: resolved" or "## Resolution".
    if (/status:\s*resolved|## Resolution/.test(content)) continue;
    const createdMatch = content.match(/created:\s*([\dT:Z.+-]+)/);
    const created = createdMatch ? Date.parse(createdMatch[1]) : NaN;
    if (Number.isNaN(created)) {
      console.error(`OWNERSHIP: fix-plan "${plan}" missing created date`);
      violations++;
      continue;
    }
    const daysOpen = (now - created) / 86400000;
    if (daysOpen > 7) {
      console.error(`OWNERSHIP: open fix-plan "${plan}" unresolved for ${daysOpen.toFixed(1)} days`);
      violations++;
    }
  }
} catch { /* not a git repo → skip the age check */ }

if (violations > 0) {
  console.error(`\nfix-plan-scan: FAIL — ${violations} ownership violations. Every problem is filed work.`);
  process.exit(1);
}
console.log('fix-plan-scan: pass — no unfiled markers, no orphaned fix-plans');