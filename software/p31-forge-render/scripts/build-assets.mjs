// build-assets.mjs — generate src/assets.mjs from the FORGE SSOT.
// The forge (software/p31-forge) owns the CSS and templates; this script
// snapshots them as JS string modules so the worker bundle is self-contained
// and workerd-safe (no node:fs at runtime). Run `npm run assets` after any
// forge CSS/template change.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const FORGE = resolve(HERE, '..', '..', 'p31-forge')
const read = (p) => JSON.stringify(readFileSync(resolve(FORGE, p), 'utf8'))

const files = [
  ['REPORT_CSS', 'booklet/report.css'],
  ['THEMES_CSS', 'booklet/report-themes.css'],
  ['LAYOUT_CSS', 'booklet/layout/layout.css'],
  ['PAGES_CSS', 'booklet/layout/pages.css'],
  ['THEME_PICKER_JS', 'booklet/theme-picker.js'],
  ['INDEX_JSON', 'booklet/layout/templates/index.json'],
]
const templates = readdirSync(resolve(FORGE, 'booklet/layout/templates')).filter((f) => f.endsWith('.json'))

const out = []
out.push('// GENERATED by build-assets.mjs from the forge SSOT. Do not edit.')
for (const [name, path] of files) out.push(`export const ${name} = ${read(path)};`)
for (const f of templates) {
  const name = `TEMPLATE_${f.replace(/\.json$/, '').toUpperCase().replace(/-/g, '_')}`
  out.push(`export const ${name} = ${read(`booklet/layout/templates/${f}`)};`)
}
out.push(`export const TEMPLATE_FILES = ${JSON.stringify(templates)};`)
writeFileSync(resolve(HERE, '..', 'src', 'assets.mjs'), out.join('\n') + '\n')
console.log(`assets.mjs generated: ${files.length} files + ${templates.length} templates`)