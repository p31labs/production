// vector.mjs — Known-answer test vector for taler_cs.wasm
// (TWO-CHALLENGE Clause Blind Schnorr over Ed25519).
//
// Gates (AXIS-1 §7, extended for the two-challenge scheme):
//   1. WASM builds                     -> via cargo (build-cbs.sh)
//   2. round-trip verify == true       -> blind -> sign -> unblind -> verify
//   3. tampered s'  -> verify == false (the property the broken
//      XOR 'return 0' stub FAILED)
//   4. tampered message -> false       (wrong-msg control)
//   5. wrong denomination key -> false (wrong-key control)
//   6. one-challenge-only forgery -> false (slot mix + random fill)
//
// Strong cross-check: issuer public key X and ephemeral nonces R_0, R_1 are
// generated by Node Web Crypto (an INDEPENDENT Ed25519 implementation) and
// fed to the wasm. Any divergence between the two implementations fails.

import { readFileSync, promises as fs } from 'node:fs';
import { webcrypto } from 'node:crypto';

const crypto = webcrypto;
// Resolve the artifact: prefer the committed prebuilt, fall back to a local build.
const CANDIDATES = [
  new URL('../src/taler_cs.wasm', import.meta.url),
  new URL('../target/wasm32-unknown-unknown/release/taler_cbs.wasm', import.meta.url),
];
let WASM = null;
for (const c of CANDIDATES) {
  try {
    await fs.access(c);
    WASM = c;
    break;
  } catch {}
}
if (!WASM) {
  console.error('FAIL: taler_cs.wasm not found (build first or commit the prebuilt)');
  process.exit(1);
}
const buf = readFileSync(WASM);

const { instance } = await WebAssembly.instantiate(buf, { env: {} });
const ex = instance.exports;
const mem = ex.memory;

// Safe region: above Rust data/stack, within the single memory page set.
const HEAP = Math.ceil(ex.__heap_base.value / 1024) * 1024;
const OFF_MSG = HEAP + 0;      // message (<=1024)
const OFF_A0 = HEAP + 2048;    // alpha_0 / scratch
const OFF_A1 = HEAP + 3072;    // alpha_1 / scratch
const OFF_B0 = HEAP + 4096;    // beta_0  / scratch
const OFF_B1 = HEAP + 5120;    // beta_1  / scratch
const OFF_R0 = HEAP + 6144;    // R_0
const OFF_R1 = HEAP + 7168;    // R_1
const OFF_X = HEAP + 8192;     // X
const OFF_RP0 = HEAP + 9216;   // R'_0 out
const OFF_RP1 = OFF_RP0 + 32;  // R'_1 out
const OFF_C0 = OFF_RP1 + 32;   // c_0 out (blinded, -> issuer)
const OFF_C1 = OFF_C0 + 32;    // c_1 out
const OFF_CP0 = OFF_C1 + 32;   // c'_0 out (kept)
const OFF_CP1 = OFF_CP0 + 32;  // c'_1 out (kept)
const OFF_S0 = HEAP + 12288;   // s_0 / s'_0
const OFF_S1 = OFF_S0 + 32;    // s_1 / s'_1

const U8 = (off, n) => new Uint8Array(mem.buffer, off, n);
const write = (off, d) => U8(off, d.length).set(d);
const read = (off, n) => U8(off, n).slice();
const rnd = () => crypto.getRandomValues(new Uint8Array(32));
const clamp32 = (seed) => {
  const x = seed.slice(0, 32);
  x[0] &= 248;
  x[31] &= 127;
  x[31] |= 64;
  return x;
};

// Derive (scalar, publicPoint) the RFC 8032 way, using Web Crypto keys.
async function ed25519Scalars() {
  const kp = await crypto.subtle.generateKey('Ed25519', true, ['sign', 'verify']);
  const jwk = await crypto.subtle.exportKey('jwk', kp.privateKey);
  const pub = new Uint8Array(Buffer.from(jwk.x, 'base64url'));
  const seed = new Uint8Array(Buffer.from(jwk.d, 'base64url'));
  const h = new Uint8Array(await crypto.subtle.digest('SHA-512', seed));
  const scalar = clamp32(h);
  return { pub, scalar };
}

// --- Issuer keypair (X) and TWO ephemeral nonces (R_0, R_1) from Web Crypto ---
const issuer = await ed25519Scalars();
const eph0 = await ed25519Scalars();
const eph1 = await ed25519Scalars();
const X = issuer.pub;
const x = issuer.scalar;
const R0 = eph0.pub;
const n0 = eph0.scalar;
const R1 = eph1.pub;
const n1 = eph1.scalar;

// --- Client blinds message m with two challenges ---
const m = new TextEncoder().encode('authorize 5 LOVE -> creator p31');
const a0 = rnd(), a1 = rnd(), b0 = rnd(), b1 = rnd();
write(OFF_MSG, m);
write(OFF_A0, a0); write(OFF_A1, a1);
write(OFF_B0, b0); write(OFF_B1, b1);
write(OFF_R0, R0); write(OFF_R1, R1);
write(OFF_X, X);
if (ex.cs_blind(OFF_MSG, m.length, OFF_A0, OFF_A1, OFF_B0, OFF_B1, OFF_R0, OFF_R1, OFF_X,
  OFF_RP0, OFF_RP1, OFF_C0, OFF_C1, OFF_CP0, OFF_CP1) !== 0) {
  console.error('FAIL: cs_blind');
  process.exit(1);
}
const rp0 = read(OFF_RP0, 32); // R'_0 in the final signature
const rp1 = read(OFF_RP1, 32); // R'_1 in the final signature
const c0 = read(OFF_C0, 32);   // blinded challenge -> issuer
const c1 = read(OFF_C1, 32);
const cp0 = read(OFF_CP0, 32); // kept by client
const cp1 = read(OFF_CP1, 32);
console.log('OK   blind: produced c0/c1 (to issuer), c\'0/c\'1 and R\'0/R\'1 (kept)');

// --- Issuer signs BOTH blinded challenges ---
write(OFF_A0, c0); write(OFF_A1, c1);
write(OFF_B0, n0); write(OFF_B1, n1);
write(OFF_X, x);
if (ex.cs_sign_blinded(OFF_A0, OFF_A1, OFF_B0, OFF_B1, OFF_X, OFF_S0, OFF_S1) !== 0) {
  console.error('FAIL: cs_sign_blinded');
  process.exit(1);
}
const s0 = read(OFF_S0, 32);
const s1 = read(OFF_S1, 32);
console.log('OK   sign: s0 = n0 + c0·x, s1 = n1 + c1·x');

// --- Client unblinds both partials ---
write(OFF_A0, s0); write(OFF_A1, s1);
write(OFF_B0, a0); write(OFF_B1, a1);
if (ex.cs_unblind(OFF_A0, OFF_A1, OFF_B0, OFF_B1, OFF_S0, OFF_S1) !== 0) {
  console.error('FAIL: cs_unblind');
  process.exit(1);
}
const sp0 = read(OFF_S0, 32);
const sp1 = read(OFF_S1, 32);
console.log('OK   unblind: s\'0 = s0 + a0, s\'1 = s1 + a1');

// --- Verify (valid signature, BOTH challenges) ---
write(OFF_MSG, m);
write(OFF_A0, cp0); write(OFF_A1, sp0);
write(OFF_B0, cp1); write(OFF_B1, sp1);
write(OFF_X, X);
write(OFF_R0, rp0); write(OFF_R1, rp1);
const valid = ex.cs_verify(OFF_MSG, m.length, OFF_A0, OFF_A1, OFF_B0, OFF_B1, OFF_X, OFF_R0, OFF_R1) === 0;
if (!valid) {
  console.error('FAIL: valid two-challenge CBS signature (cross-checked w/ Web Crypto points) rejected');
  process.exit(1);
}
console.log('OK   verify: round-trip signature VALID (wasm == independent Ed25519)');

// --- Verify (tampered s'0) -> must be INVALID (catches return-0 bug) ---
const tampered = sp0.slice();
tampered[0] ^= 0xff;
write(OFF_A0, cp0); write(OFF_A1, tampered);
if (ex.cs_verify(OFF_MSG, m.length, OFF_A0, OFF_A1, OFF_B0, OFF_B1, OFF_X, OFF_R0, OFF_R1) === 0) {
  console.error('FAIL: tampered signature accepted (broken-verify regression)');
  process.exit(1);
}
console.log('OK   verify: tampered s\'0 REJECTED (no return-0 bug)');

// --- Verify (wrong message) -> must be INVALID ---
const wrongMsg = new TextEncoder().encode('authorize 5000 LOVE -> attacker');
write(OFF_MSG, wrongMsg);
write(OFF_A0, cp0); write(OFF_A1, sp0);
if (ex.cs_verify(OFF_MSG, wrongMsg.length, OFF_A0, OFF_A1, OFF_B0, OFF_B1, OFF_X, OFF_R0, OFF_R1) === 0) {
  console.error('FAIL: wrong-message signature accepted');
  process.exit(1);
}
console.log('OK   verify: wrong message REJECTED');

// --- Verify (wrong denomination key X') -> must be INVALID ---
const other = await ed25519Scalars();
const X2 = other.pub;
write(OFF_X, X2);
write(OFF_MSG, m);
if (ex.cs_verify(OFF_MSG, m.length, OFF_A0, OFF_A1, OFF_B0, OFF_B1, OFF_X, OFF_R0, OFF_R1) === 0) {
  console.error('FAIL: wrong-denomination-key signature accepted');
  process.exit(1);
}
console.log('OK   verify: wrong denomination key REJECTED');
write(OFF_X, X);

// --- Verify (one-challenge-only forgery) -> must be INVALID ---
// A single valid challenge pair cannot pass unless BOTH slots are the same
// valid pair (which attests nothing new). Random slot-1 fill must fail.
write(OFF_A0, cp0); write(OFF_A1, sp0);
write(OFF_B0, rnd()); write(OFF_B1, rnd());
write(OFF_R0, rp0); write(OFF_R1, rnd());
if (ex.cs_verify(OFF_MSG, m.length, OFF_A0, OFF_A1, OFF_B0, OFF_B1, OFF_X, OFF_R0, OFF_R1) === 0) {
  console.error('FAIL: one-challenge-only forgery accepted (random slot-1 fill)');
  process.exit(1);
}
console.log('OK   verify: one-challenge-only forgery REJECTED');
write(OFF_B0, cp1); write(OFF_B1, sp1);
write(OFF_R1, rp1);

// --- Sanity: random (c', s') both slots -> INVALID (catches always-true verify) ---
write(OFF_A0, rnd()); write(OFF_A1, rnd());
write(OFF_B0, rnd()); write(OFF_B1, rnd());
if (ex.cs_verify(OFF_MSG, m.length, OFF_A0, OFF_A1, OFF_B0, OFF_B1, OFF_X, OFF_R0, OFF_R1) === 0) {
  console.error('FAIL: random signature accepted (verify always-true)');
  process.exit(1);
}
console.log('OK   verify: random signature REJECTED');

// --- Self-consistency over many random trials ---
for (let i = 0; i < 12; i++) {
  const mm = crypto.getRandomValues(new Uint8Array(1 + (i % 40)));
  const aa0 = rnd(), aa1 = rnd(), bb0 = rnd(), bb1 = rnd();
  write(OFF_MSG, mm);
  write(OFF_A0, aa0); write(OFF_A1, aa1);
  write(OFF_B0, bb0); write(OFF_B1, bb1);
  write(OFF_R0, R0); write(OFF_R1, R1);
  write(OFF_X, X);
  if (ex.cs_blind(OFF_MSG, mm.length, OFF_A0, OFF_A1, OFF_B0, OFF_B1, OFF_R0, OFF_R1, OFF_X,
    OFF_RP0, OFF_RP1, OFF_C0, OFF_C1, OFF_CP0, OFF_CP1) !== 0) {
    console.error('FAIL: blind trial', i);
    process.exit(1);
  }
  const cc0 = read(OFF_C0, 32), cc1 = read(OFF_C1, 32);
  const ccp0 = read(OFF_CP0, 32), ccp1 = read(OFF_CP1, 32);
  const rrp0 = read(OFF_RP0, 32), rrp1 = read(OFF_RP1, 32);
  write(OFF_A0, cc0); write(OFF_A1, cc1);
  write(OFF_B0, n0); write(OFF_B1, n1);
  write(OFF_X, x);
  if (ex.cs_sign_blinded(OFF_A0, OFF_A1, OFF_B0, OFF_B1, OFF_X, OFF_S0, OFF_S1) !== 0) {
    console.error('FAIL: sign trial', i);
    process.exit(1);
  }
  write(OFF_A0, read(OFF_S0, 32)); write(OFF_A1, read(OFF_S1, 32));
  write(OFF_B0, aa0); write(OFF_B1, aa1);
  if (ex.cs_unblind(OFF_A0, OFF_A1, OFF_B0, OFF_B1, OFF_S0, OFF_S1) !== 0) {
    console.error('FAIL: unblind trial', i);
    process.exit(1);
  }
  write(OFF_MSG, mm);
  write(OFF_A0, ccp0); write(OFF_A1, read(OFF_S0, 32));
  write(OFF_B0, ccp1); write(OFF_B1, read(OFF_S1, 32));
  write(OFF_X, X);
  write(OFF_R0, rrp0); write(OFF_R1, rrp1);
  if (ex.cs_verify(OFF_MSG, mm.length, OFF_A0, OFF_A1, OFF_B0, OFF_B1, OFF_X, OFF_R0, OFF_R1) !== 0) {
    console.error('FAIL: round-trip trial', i);
    process.exit(1);
  }
}
console.log('OK   12 randomized two-challenge round-trips all VALID');

console.log('\nALL GATES PASSED — taler_cs.wasm is a real, verified TWO-CHALLENGE Clause Blind Schnorr.');